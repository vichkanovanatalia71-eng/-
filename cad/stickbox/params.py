@dataclass
class Derived:
    pass


def derived():
    d = {}
    W_, D_, H_ = v(W), v(D), v(H)
    tan_c = math.tan(math.radians(v(DRAFT_CAV)))
    tan_p = math.tan(math.radians(v(DRAFT_POCKET)))

    # Порожнина (низ)
    cav_x0 = -W_ / 2 + v(T_LEFT)
    cav_x1 = cav_x0 + v(CAV)
    cav_xc = (cav_x0 + cav_x1) / 2
    cav_y0, cav_y1 = -v(CAV) / 2, v(CAV) / 2
    d.update(cav_x0=cav_x0, cav_x1=cav_x1, cav_xc=cav_xc, cav_y0=cav_y0, cav_y1=cav_y1)
    d["t_front_back"] = D_ / 2 - v(CAV) / 2

    # Кришка / ребейт
    z_reb = v(FLANGE_T) + v(LID_RECESS)  # глибина ребейту (=верх фланця)
    d["z_reb"] = z_reb
    d["reb"] = v(CAV) + 2 * v(SHOULDER)
    d["r_reb"] = v(R_CAV) + v(SHOULDER)
    d["flange"] = d["reb"] - 2 * v(LID_GAP)
    d["r_flange"] = d["r_reb"] - v(LID_GAP)
    d["plug"] = v(CAV) - 2 * v(PLUG_GAP)
    d["r_plug"] = v(R_CAV) - v(PLUG_GAP)
    plug_h = v(HOOK_H) + v(LAND_H) + v(GROOVE_W) + v(TOP_LIP)
    d["plug_h"] = plug_h
    d["lid_t"] = v(FLANGE_T) + plug_h
    d["z_plug_top"] = v(LID_RECESS) + d["lid_t"]
    # канавка (координати кришки, z=0 — низ кришки)
    g0 = v(FLANGE_T) + v(HOOK_H) + v(LAND_H)
    d["groove_z0"], d["groove_z1"] = g0, g0 + v(GROOVE_W)
    gz_mid = (d["groove_z0"] + d["groove_z1"]) / 2
    # півширина пробки на висоті середини канавки (пробка має ухил DRAFT_CAV)
    plug_half_mid = d["plug"] / 2 - (gz_mid - v(FLANGE_T)) * tan_c
    cav_half_mid = v(CAV) / 2 - (gz_mid + v(LID_RECESS) - z_reb) * tan_c
    groove_depth = v(ORING_CS) - v(ORING_SQUEEZE) - (cav_half_mid - plug_half_mid)
    d["groove_depth"] = groove_depth
    d["groove_bottom_half"] = plug_half_mid - groove_depth
    d["gland_depth"] = cav_half_mid - d["groove_bottom_half"]
    d["squeeze_pct"] = (v(ORING_CS) - d["gland_depth"]) / v(ORING_CS) * 100
    d["groove_fill_pct"] = (math.pi / 4 * v(ORING_CS) ** 2) / (v(GROOVE_W) * d["gland_depth"]) * 100
    r_gb = d["r_plug"] - (gz_mid - v(FLANGE_T)) * tan_c - groove_depth
    d["r_groove_bottom"] = r_gb
    side = 2 * d["groove_bottom_half"]
    perim = 4 * (side - 2 * r_gb) + 2 * math.pi * r_gb
    d["groove_perimeter"] = perim
    # відріз губчастого шнура: довжина по центру перерізу з розтягом 3% (щільно сидить у канавці)
    center_len = perim + math.pi * v(ORING_CS)
    d["seal_center_len"] = center_len
    d["seal_cut_len"] = center_len / 1.03
    d["oring_stretch_pct"] = 3.0
    d["recess_top"] = z_reb + v(HOOK_H)
    d["recess_x"] = (cav_x0 + cav_x1) / 2 if v(RECESS_ON_AXIS) else 0.0
    if v(FULL_LID_ON):
        # v3.5: фланець кришки = габарит дна (з тіньовим зазором LID_GAP); пробка — Г-профіль резервуара з зазором PLUG_GAP
        d["flange_w"], d["flange_d"] = W_ - 2 * v(LID_GAP), D_ - 2 * v(LID_GAP)
        d["r_flange"] = v(R_V) - v(LID_GAP)
        g0 = v(FLANGE_T) + v(HOOK_H) + v(LAND_H)
        d["groove_z0"], d["groove_z1"] = g0, g0 + v(GROOVE_W)
        d["groove_depth"] = v(ORING_CS) - v(ORING_SQUEEZE) - v(PLUG_GAP)
        d["gland_depth"] = v(PLUG_GAP) + d["groove_depth"]
        d["squeeze_pct"] = (v(ORING_CS) - d["gland_depth"]) / v(ORING_CS) * 100
        d["groove_fill_pct"] = (math.pi / 4 * v(ORING_CS) ** 2) / (v(GROOVE_W) * d["gland_depth"]) * 100

    # Кишеня девайса
    liner_in_x = v(DEV_T) + 2 * v(DEV_CLEAR)
    liner_in_y = v(DEV_W) + 2 * v(DEV_CLEAR)
    pocket_x = liner_in_x + 2 * v(LINER_WALL)
    pocket_y = liner_in_y + 2 * v(LINER_WALL)
    d.update(liner_in_x=liner_in_x, liner_in_y=liner_in_y, pocket_x=pocket_x, pocket_y=pocket_y)
    dev_z0 = H_ + v(DEV_PROTRUDE) - v(DEV_L)
    pocket_floor = dev_z0 - v(LINER_FLOOR)   # v2.5: дно кишені = низ девайса − повстяна підкладка
    d.update(dev_z0=dev_z0, pocket_floor=pocket_floor, pocket_depth=H_ - pocket_floor)
    px = W_ / 2 - v(T_RIGHT) - pocket_x / 2
    py = -D_ / 2 + v(T_FRONT_POCKET) + pocket_y / 2
    d.update(pocket_cx=px, pocket_cy=py)
    d["pocket_inset_floor"] = d["pocket_depth"] * tan_p
    d["liner_wall_bottom"] = v(LINER_WALL) - d["pocket_inset_floor"]

    # Стеля порожнини
    z_ceil_c = H_ - v(T_TOP)
    d["z_ceil_c"] = z_ceil_c
    half_top = v(CAV) / 2 - (z_ceil_c - z_reb) * tan_c
    s = v(DOME_SAG)
    d["r_dome"] = (half_top ** 2 + s ** 2) / (2 * s)
    d["z_ceil_edge"] = z_ceil_c - s
    if v(FULL_LID_ON):
        # v3.5: Г-профіль резервуара на висоті низу корпусу zb (= верх фланця кришки); вище — ухил DRAFT_CAV
        zb = z_reb
        d["zb"] = zb
        d["Lx0"] = -W_ / 2 + v(WALL_T)
        d["Lx1"] = W_ / 2 - v(WALL_T)
        d["Ly0"] = -D_ / 2 + v(WALL_FRONT_T)
        d["Ly1"] = D_ / 2 - (v(WALL_FRONT_T) if (v(LID_RECT_ON) and v(SOCK_SYM)) else v(WALL_T))
        # грані колонки тримача з боку резервуара: перегородка до кишені ≥ WALL_PART_T на всій висоті (обидва ухили)
        pl = lambda z: px - pocket_x / 2 + (H_ - z) * tan_p            # ліва стінка кишені (кишеня вужча донизу)
        pb = lambda z: py + pocket_y / 2 - (H_ - z) * tan_p            # задній торець кишені
        d["Lxc"] = min(pl(z) - v(WALL_PART_T) - (z - zb) * tan_c for z in (pocket_floor, z_ceil_c))
        d["Lyc"] = max(pb(z) + v(WALL_PART_T) - (z - zb) * tan_c for z in (pocket_floor, z_ceil_c))
        d["L_r_out"], d["L_r_col"] = v(CAV_R_OUT), v(CAV_R_COL)
        # купол стелі: стріла DOME_SAG_FAR до найдальшого кута Г-профілю від осі отвору
        rf = max(math.hypot(x - cav_xc, y) for x in (d["Lx0"], d["Lx1"]) for y in (d["Ly0"], d["Ly1"]))
        d["r_dome"] = rf ** 2 / (2 * v(DOME_SAG_FAR))
        d["z_ceil_edge"] = z_ceil_c - v(DOME_SAG_FAR)
        # довжина шнура: середня лінія стиснутого шнура = Г-профіль на висоті середини канавки, зміщений на gland/2
        gz = (d["groove_z0"] + d["groove_z1"]) / 2
        o = (gz - zb) * tan_c + d["gland_depth"] / 2
        bw, bh = (d["Lx1"] - d["Lx0"]) - 2 * o, (d["Ly1"] - d["Ly0"]) - 2 * o
        rsum = 5 * max(0.5, v(CAV_R_OUT) - o) + (v(CAV_R_COL) + o)
        d["seal_center_len"] = 2 * (bw + bh) - (2 - math.pi / 2) * rsum
        if v(LID_RECT_ON):
            # v3.6: прямокутна пробка: гніздо внизу корпусу — повний прямокутник до z_sock; колонка тримача — вище
            d["z_sock"] = zb + d["plug_h"] + v(SOCK_TOP_GAP)
            d["col_slab"] = pocket_floor - d["z_sock"]          # бетон між дном кишені й низом колонки
            r_c = max(0.5, v(CAV_R_OUT) - o)
            d["seal_center_len"] = 2 * (bw + bh) - (8 - 2 * math.pi) * r_c
        d["seal_cut_len"] = d["seal_center_len"] / 1.03
        d["groove_perimeter"] = d["seal_center_len"] - 2 * math.pi * d["gland_depth"] / 2

    # Перегородка порожнина ↔ кишеня (на рівні дна кишені і біля стелі)
    cav_right_at = lambda z: cav_x1 - max(0.0, z - z_reb) * tan_c
    pocket_left_at = lambda z: px - pocket_x / 2 + (H_ - z) * tan_p
    d["partition_at_floor"] = pocket_left_at(pocket_floor) - cav_right_at(pocket_floor)
    d["partition_at_ceil"] = pocket_left_at(z_ceil_c) - cav_right_at(z_ceil_c)
    # лоток кришки
    d["tray"] = d["plug"] - 2 * v(SKIRT_W)
    d["r_tray"] = max(3.0, d["r_plug"] - v(SKIRT_W))
    d["tray_depth"] = d["lid_t"] - v(LID_FLOOR)
    # полегшувальна порожнина (низ, з ухилом 1°): x від перегородки до правої стінки, y від кишені до задньої стінки
    reb_right = (cav_x0 + cav_x1) / 2 + d["reb"] / 2
    rx0 = max(cav_x1 + v(RELIEF_WALL), (reb_right + v(RL_WEB) + v(RL_SHOULDER)) if v(RL_ON) else -1e9)
    rx1 = W_ / 2 - v(RELIEF_OUT)
    ry0 = py + pocket_y / 2 + v(RELIEF_WALL)
    ry1 = D_ / 2 - v(RELIEF_OUT)
    d.update(rel_x0=rx0, rel_x1=rx1, rel_y0=ry0, rel_y1=ry1, rel_top=H_ - v(RELIEF_TOP))
    # кришечка полегшувальної порожнини
    rw, rh = rx1 - rx0, ry1 - ry0
    # v3.0: плече Г-резервуара
    d["arm_x1"], d["arm_y0"], d["arm_y1"] = rx1, ry0, cav_y1
    d["arm_sill_z"] = v(LID_RECESS) + d["groove_z1"] + v(ARM_SILL_MARGIN)   # верх канавки (абс.) + запас
    if v(WALL_ON):
        # v3.4: верхня (тонкостінна) частина резервуара: розміри на верху перехідної смуги z = up_zt
        d["up_x0"] = -v(W) / 2 + v(WALL_T)
        d["up_y0"] = -v(D) / 2 + v(WALL_FRONT_T)
        d["up_y1"] = v(D) / 2 - v(WALL_T)
        step = max(cav_x0 - d["up_x0"], cav_y0 - d["up_y0"], d["up_y1"] - cav_y1)
        d["up_step"] = step
        # кути — еквідистанта шийки (R_CAV + крок): чашка сердечника підтискається рівно на step і в кутах (а не 6.6 мм при R9);
        # вертикальні кути корпусу лишаються товщими (~9 мм) — саме туди припадають удари при падінні
        d["up_r"] = v(R_CAV) + step
        d["arm_r"] = v(R_V) - v(WALL_T)                      # кути плеча концентричні з R14 корпусу → стінка WALL_T і в куті
        d["up_z0"] = d["arm_sill_z"]
        d["up_zt"] = d["up_z0"] + step * math.tan(math.radians(v(WALL_STEP_DEG)))
        d["arm_x1"] = v(W) / 2 - v(WALL_T)                   # права стінка плеча — WALL_T
        # задня стінка плеча лишається на лінії шийки (cav_y1): суцільний силіконовий блок плеча виходить через шийку без підтиску
    d["rl_reb_w"], d["rl_reb_h"] = rw + 2 * v(RL_SHOULDER), rh + 2 * v(RL_SHOULDER)
    d["rl_r_reb"] = v(RELIEF_R) + v(RL_SHOULDER)
    d["rl_z_reb"] = v(RL_FLANGE_T) + v(LID_RECESS)
    d["rl_flange_w"], d["rl_flange_h"] = d["rl_reb_w"] - 2 * v(RL_GAP), d["rl_reb_h"] - 2 * v(RL_GAP)
    d["rl_plug_w"], d["rl_plug_h"] = rw - 2 * v(RL_PLUG_GAP), rh - 2 * v(RL_PLUG_GAP)
    d["rl_r_plug"] = v(RELIEF_R) - v(RL_PLUG_GAP)
    d["rl_plug_len"] = v(RL_LAND) + v(RL_GROOVE_W) + v(RL_LIP)
    d["rl_t"] = v(RL_FLANGE_T) + d["rl_plug_len"]
    d["rl_recess_top"] = d["rl_z_reb"] + v(RL_HOOK_H)
    d["rl_groove_z0"] = d["rl_z_reb"] + v(RL_LAND)
    # проріз-вітрина та органи керування девайса (координати корпусу)
    dev_top = dev_z0 + v(DEV_L)     # v2.8: органи керування відраховуються від торця зі стіком (верх девайса)
    d["led_z1"] = dev_top - v(DEV_CTRL_Z0)      # верх смужки
    d["btn_z1"] = dev_top - v(DEV_BTN_Z0)       # межа смужка/кнопка
    d["btn_z0"] = dev_top - v(DEV_CTRL_Z1)      # низ кнопки
    d["slot_straight_z0"] = H_ - v(SLOT_DEPTH) + v(SLOT_W) / 2
    d["slot_tip_z"] = H_ - v(SLOT_DEPTH)
    d["rl_groove_depth"] = v(RL_CS) - v(RL_SQUEEZE) - v(RL_PLUG_GAP)
    gp = 2 * (rw - 2 * v(RL_PLUG_GAP) - 2 * d["rl_groove_depth"]) + 2 * (rh - 2 * v(RL_PLUG_GAP) - 2 * d["rl_groove_depth"]) \
        - (8 - 2 * math.pi) * max(1.0, v(RELIEF_R) - v(RL_PLUG_GAP) - d["rl_groove_depth"])
    d["rl_seal_cut_len"] = (gp + math.pi * v(RL_CS)) / 1.03
    return d


